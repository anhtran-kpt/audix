import type { Metadata } from "next";
import { Lexend } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "@/providers/theme-provider";
import { SidebarProvider } from "@/components/ui/sidebar";
import { AppSidebar } from "@/components/features/app-sidebar";
import { Header } from "@/components/features/header";
import AudioPlayer from "@/components/features/audio-player";
import { LayoutWithPlayer } from "@/components/features/layout-with-player";
import { AuthProvider } from "@/providers/auth-provider";
import prisma from "@/lib/prisma";
import { getServerSession } from "next-auth";
import { authOptions } from "./api/auth/[...nextauth]/route";

const lexendSans = Lexend({
  subsets: ["vietnamese"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const session = await getServerSession(authOptions);

  const [playlists, followingArtists] = await Promise.all([
    prisma.playlist.findMany({
      where: {
        userId: session?.user.id,
      },
      select: {
        id: true,
        title: true,
        imageId: true,
        user: {
          select: {
            image: true,
            id: true,
            name: true,
          },
        },
      },
    }),
    prisma.userLikedArtist
      .findMany({
        where: {
          userId: session?.user.id,
        },
        select: {
          artist: {
            select: {
              id: true,
              name: true,
              imageId: true,
            },
          },
        },
      })
      .then((data) => data.map((item) => item.artist)),
  ]);

  return (
    <html
      lang="en"
      className={`${lexendSans.className} scroll-smooth overflow-x-hidden overflow-y-scroll overscroll-none`}
      data-scroll-behavior="smooth"
      suppressHydrationWarning
    >
      <body className="antialiased min-h-screen">
        <ThemeProvider
          attribute="class"
          defaultTheme="dark"
          enableSystem
          disableTransitionOnChange
        >
          <AuthProvider session={session}>
            <SidebarProvider>
              <AppSidebar
                playlists={playlists}
                followingArtists={followingArtists}
              />
              <div className="flex flex-col min-w-0 flex-1">
                <Header />
                <LayoutWithPlayer>
                  <main className="flex-1 p-12 space-y-8 mt-15">
                    {children}
                  </main>
                </LayoutWithPlayer>
              </div>
              <AudioPlayer />
            </SidebarProvider>
          </AuthProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
